/** Rows 0–7 of a character as 5-bit masks (bit 4 = left column); blank outside 0x20–0x7F. */
export function glyphRows(code: number): number[] {
  const rows = [0, 0, 0, 0, 0, 0, 0, 0];
  if (code < 0x20 || code > 0x7f) return rows;
  const at = (code - 0x20) * 10;
  for (let c = 0; c < 5; c++) {
    const col = Number.parseInt(ROM.slice(at + 2 * c, at + 2 * c + 2), 16);
    for (let r = 0; r < 8; r++) if ((col >> r) & 1) rows[r] = (rows[r] ?? 0) | (0x10 >> c);
  }
  return rows;
}
