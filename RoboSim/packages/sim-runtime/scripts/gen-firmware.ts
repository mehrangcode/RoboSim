// Assembles src/firmware/sources.ts into src/firmware/generated.ts (Intel HEX strings).
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { toIntelHex } from '@robosim/board-avr-uno';
import { assemble } from 'avr8js/dist/cjs/utils/assembler.js';
import { FIRMWARE_SOURCES } from '../src/firmware/sources.ts';

const out: Record<string, string> = {};
for (const [id, source] of Object.entries(FIRMWARE_SOURCES)) {
  const { errors, bytes } = assemble(source);
  if (errors.length > 0) throw new Error(`${id}: ${errors.join('; ')}`);
  out[id] = toIntelHex(bytes);
}
const body = Object.entries(out)
  .map(([id, hex]) => `  ${id}: ${JSON.stringify(hex)},`)
  .join('\n');
writeFileSync(
  join(import.meta.dirname, '../src/firmware/generated.ts'),
  `// Generated by scripts/gen-firmware.ts from sources.ts — do not edit.\nimport type { FirmwareId } from './sources.js';\n\nexport const FIRMWARE_HEX: Record<FirmwareId, string> = {\n${body}\n};\n`,
);
console.warn(`Wrote ${Object.keys(out).length} firmware images.`);
