#!/usr/bin/env node
// Turns avr8js's instruction interpreter (an if/else chain that tests up to ~86 opcode masks per instruction)
// into a table-dispatched one: every 16-bit opcode is decoded once into the index of the first branch that
// matches it, and execution switches on that index. Branch bodies are copied verbatim, so behaviour is
// identical by construction; test/decoder.test.ts checks the output against the pinned avr8js and runs
// both interpreters side by side on every opcode.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HEADER_START = /^ {4}(?:else )?if \(/;

/** Source of avr8js's interpreter as installed (ESM build). */
export function avr8jsInstructionSource(): { version: string; source: string } {
  const require = createRequire(import.meta.url);
  const pkg = require.resolve('avr8js/package.json');
  const { version } = JSON.parse(readFileSync(pkg, 'utf8')) as { version: string };
  return { version, source: readFileSync(join(dirname(pkg), 'dist/esm/cpu/instruction.js'), 'utf8') };
}

export function generateDecoder(version: string, source: string): string {
  const lines = source.split('\n');
  const start = lines.findIndex((l) => l.startsWith('export function avrInstruction(cpu) {'));
  const helperEnd = start;
  const helper = lines
    .slice(
      lines.findIndex((l) => l.startsWith('function isTwoWordInstruction')),
      helperEnd,
    )
    .join('\n')
    .replace(
      'function isTwoWordInstruction(opcode) {',
      'function isTwoWordInstruction(opcode: number): boolean {',
    )
    .trimEnd();
  const tail = lines.findIndex(
    (l, i) => i > start && l === '    cpu.pc = (cpu.pc + 1) % cpu.progMem.length;',
  );
  if (start < 0 || tail < 0 || lines[start + 1] !== '    const opcode = cpu.progMem[cpu.pc];')
    throw new Error('avr8js interpreter layout changed: update scripts/gen-decoder.ts');

  const branches: { cond: string; body: string[] }[] = [];
  for (let i = start + 2; i < tail; i++) {
    const line = lines[i] ?? '';
    if (HEADER_START.test(line)) {
      // A condition may wrap over several lines; it ends at the line that opens the body.
      let header = line.trim();
      while (!header.endsWith(') {')) header += ` ${(lines[++i] ?? '').trim()}`;
      branches.push({ cond: header.replace(/^(?:else )?if \(/, '').slice(0, -' {'.length - 1), body: [] });
    } else if (line === '    }') continue;
    else if (branches.length === 0) throw new Error(`unexpected line ${i + 1}: ${line}`);
    else branches.at(-1)?.body.push(line);
  }
  if (
    lines.slice(tail, tail + 3).join('\n') !==
    '    cpu.pc = (cpu.pc + 1) % cpu.progMem.length;\n    cpu.cycles++;\n}'
  )
    throw new Error('avr8js interpreter tail changed: update scripts/gen-decoder.ts');

  const decode = branches.map((b, i) => `  if (${b.cond}) return ${i + 1};`).join('\n');
  const cases = branches
    .map((b, i) =>
      [`    case ${i + 1}: {`, ...b.body.map((l) => `  ${l}`), '      break;', '    }'].join('\n'),
    )
    .join('\n');
  return `// Generated by scripts/gen-decoder.ts from avr8js ${version} (dist/esm/cpu/instruction.js) — do not edit.
// Branch bodies are avr8js's, under its licence: MIT, Copyright (c) Uri Shaked and contributors.
/* eslint-disable */
// @ts-nocheck
import type { CPU } from 'avr8js';

export const AVR8JS_VERSION = '${version}';

${helper}

/** Index of the first avr8js branch that matches \`opcode\` (0: none, which executes as a NOP). */
function decode(opcode: number): number {
${decode}
  return 0;
}

const TABLE = new Uint8Array(0x10000);
for (let opcode = 0; opcode < 0x10000; opcode++) TABLE[opcode] = decode(opcode);

/** Executes one instruction, exactly as avr8js's \`avrInstruction\`. */
export function avrInstruction(cpu: CPU): void {
  const opcode = cpu.progMem[cpu.pc];
  switch (TABLE[opcode]) {
${cases}
  }
  cpu.pc = (cpu.pc + 1) % cpu.progMem.length;
  cpu.cycles++;
}
`;
}

const TARGET = fileURLToPath(new URL('../src/decoder.generated.ts', import.meta.url));

/** The committed generated decoder. */
export function committedDecoder(): string {
  return readFileSync(TARGET, 'utf8');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { version, source } = avr8jsInstructionSource();
  const target = TARGET;
  writeFileSync(target, generateDecoder(version, source));
  console.warn(`Wrote ${target} from avr8js ${version}.`);
}
