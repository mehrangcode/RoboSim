#!/usr/bin/env node
// Compiles the built-in demo sketches (packages/sim-runtime/src/firmware/sketches.ts) with the build service and
// writes their Intel HEX to generated.ts. Trusted sources: no sandbox. The demo-firmware test fails on drift.
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FIRMWARE_SKETCHES } from '../../../packages/sim-runtime/src/firmware/sketches.ts';
import { demoBuildRequest } from '../src/demo.ts';
import { Compiler } from '../dist/compiler.js';

const target = fileURLToPath(
  new URL('../../../packages/sim-runtime/src/firmware/generated.ts', import.meta.url),
);
const cacheDir = await mkdtemp(join(tmpdir(), 'robosim-demo-firmware-'));
try {
  const compiler = await Compiler.create({ cacheDir, sandbox: false });
  const out: Record<string, string> = {};
  for (const [id, sketch] of Object.entries(FIRMWARE_SKETCHES)) {
    const result = await compiler.build(demoBuildRequest(sketch));
    const hex = result.artifact && (await compiler.readArtifact(result.artifact.sha256));
    if (!hex || result.diagnostics.length > 0)
      throw new Error(
        `${id}: ${result.diagnostics.map((d) => `${d.line}:${d.column} ${d.message}`).join('; ')}`,
      );
    out[id] = hex;
  }
  // Same shape Prettier gives it (single quotes, value on its own line past printWidth 110).
  const body = Object.entries(out)
    .map(([id, hex]) => {
      const value = `'${hex.replaceAll('\n', '\\n')}'`;
      const line = `  ${id}: ${value},`;
      return line.length <= 110 ? line : `  ${id}:\n    ${value},`;
    })
    .join('\n');
  await writeFile(
    target,
    `// Generated by apps/compiler (pnpm firmware:gen) from sketches.ts — do not edit.\n// Toolchain ${compiler.toolchain.id}: avr-gcc ${compiler.toolchain.gccVersion}, arduino:avr core + libraries per apps/compiler/toolchain.lock.json.\nimport type { FirmwareId } from './sketches.js';\n\nexport const FIRMWARE_HEX: Record<FirmwareId, string> = {\n${body}\n};\n`,
  );
  console.warn(`Wrote ${Object.keys(out).length} firmware images.`);
} finally {
  await rm(cacheDir, { recursive: true, force: true });
}
